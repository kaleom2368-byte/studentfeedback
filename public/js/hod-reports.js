document.addEventListener('DOMContentLoaded', () => {
    loadReportsData();
});

async function loadReportsData() {
    try {
        const res = await fetch('/hod/department-users');
        const data = await res.json();
        
        if (!data.success) {
            alert('Failed to load department users');
            return;
        }

        const faculty = data.faculty || [];
        
        // Populate faculty selects
        const selects = document.querySelectorAll('select');
        selects.forEach(select => {
            select.innerHTML = '<option value="">Select Faculty</option>';
            faculty.forEach(f => {
                select.innerHTML += `<option value="${f.faculty_id}">${f.name}</option>`;
            });
        });

        // Enable buttons
        document.getElementById('btn-dept-report').addEventListener('click', () => {
            downloadText('Department_Report.txt', 'Department Summary Report\n\nGenerated by HOD Portal.\n\nNote: For detailed reporting, check the dashboard metrics.');
        });

        document.getElementById('btn-faculty-report').addEventListener('click', () => {
            const select = document.getElementById('faculty-select-report');
            if (!select.value) { alert('Please select a faculty member.'); return; }
            const name = select.options[select.selectedIndex].text;
            downloadText(`${name}_Report.txt`, `Performance Report for ${name}\n\nGenerated by HOD Portal.`);
        });

        document.getElementById('btn-appreciation').addEventListener('click', () => {
            const select = document.getElementById('faculty-select-appreciation');
            if (!select.value) { alert('Please select a faculty member.'); return; }
            const name = select.options[select.selectedIndex].text;
            const text = document.getElementById('appreciation-text').value;
            downloadText(`${name}_Appreciation.txt`, `To: ${name}\n\n${text}`);
        });

        document.getElementById('btn-improvement').addEventListener('click', () => {
            const select = document.getElementById('faculty-select-improvement');
            if (!select.value) { alert('Please select a faculty member.'); return; }
            const name = select.options[select.selectedIndex].text;
            const text = document.getElementById('improvement-text').value;
            downloadText(`${name}_Improvement.txt`, `To: ${name}\n\n${text}`);
        });

    } catch (err) {
        console.error('Error loading reports data', err);
    }
}

function downloadText(filename, text) {
    const element = document.createElement('a');
    element.setAttribute('href', 'data:text/plain;charset=utf-8,' + encodeURIComponent(text));
    element.setAttribute('download', filename);
    element.style.display = 'none';
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
}
